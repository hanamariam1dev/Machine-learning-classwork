# Practical Engineering Case Study: Pump Condition Classification
# ============================================================

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.pipeline import Pipeline

from sklearn.tree import DecisionTreeClassifier, plot_tree
from sklearn.ensemble import RandomForestClassifier, AdaBoostClassifier
from sklearn.svm import SVC
from sklearn.naive_bayes import GaussianNB

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    confusion_matrix,
    classification_report
)

# ------------------------------------------------------------
# PART 1: CREATE A DEMONSTRATION PUMP DATASET
# ------------------------------------------------------------

# IMPORTANT:
# These are synthetic demonstration records, not real sensor logs.
# Replace this section with labelled historical pump records
# when real data is available.

np.random.seed(42)

def create_pump_data(number_of_records=100):

    records = []

    pump_conditions = {
        "Normal": {
            "vibration": (1.8, 0.5),
            "rpm": (1500, 60),
            "temperature": (55, 6),
            "pressure": (5.5, 0.4),
            "hours": (1500, 400)
        },

        "Warning": {
            "vibration": (4.2, 0.7),
            "rpm": (1400, 70),
            "temperature": (72, 7),
            "pressure": (4.6, 0.4),
            "hours": (4000, 700)
        },

        "Fault": {
            "vibration": (7.0, 0.8),
            "rpm": (1300, 80),
            "temperature": (90, 8),
            "pressure": (3.8, 0.4),
            "hours": (7000, 900)
        }
    }

    for condition, values in pump_conditions.items():

        for i in range(number_of_records):

            vibration = np.random.normal(*values["vibration"])
            rpm = np.random.normal(*values["rpm"])
            temperature = np.random.normal(*values["temperature"])
            pressure = np.random.normal(*values["pressure"])
            hours = np.random.normal(*values["hours"])

            records.append([
                max(0, vibration),
                max(0, rpm),
                max(0, temperature),
                max(0, pressure),
                max(0, hours),
                condition
            ])

    columns = [
        "Vibration",
        "RPM",
        "Temperature",
        "Pressure",
        "Operating_Hours",
        "Condition"
    ]

    return pd.DataFrame(records, columns=columns)


# Generate 300 demonstration records
df = create_pump_data(100)

# Save dataset as CSV
df.to_csv("pump_condition_data.csv", index=False)

print("\n========== PUMP DATASET ==========")
print(df.head())

print("\nDataset shape:", df.shape)

print("\nCondition distribution:")
print(df["Condition"].value_counts())


# ------------------------------------------------------------
# PART 2: DATA PREPROCESSING
# ------------------------------------------------------------

# Input features
X = df[
    [
        "Vibration",
        "RPM",
        "Temperature",
        "Pressure",
        "Operating_Hours"
    ]
]

# Target output
y = df["Condition"]

# Split dataset into training and testing data
X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.30,
    random_state=42,
    stratify=y
)

print("\n========== DATA SPLITTING ==========")
print("Training records:", len(X_train))
print("Testing records:", len(X_test))


# ------------------------------------------------------------
# PART 3: BUILD MACHINE LEARNING MODELS
# ------------------------------------------------------------

# AdaBoost compatibility with different scikit-learn versions
try:
    ada_model = AdaBoostClassifier(
        estimator=DecisionTreeClassifier(max_depth=1),
        n_estimators=50,
        learning_rate=0.5,
        random_state=42
    )
except TypeError:
    ada_model = AdaBoostClassifier(
        base_estimator=DecisionTreeClassifier(max_depth=1),
        n_estimators=50,
        learning_rate=0.5,
        random_state=42
    )

models = {

    "Decision Tree": DecisionTreeClassifier(
        max_depth=4,
        random_state=42
    ),

    "Random Forest": RandomForestClassifier(
        n_estimators=100,
        max_depth=5,
        random_state=42
    ),

    "SVM": Pipeline([
        ("scaler", StandardScaler()),
        ("model", SVC(kernel="rbf"))
    ]),

    "Naive Bayes": Pipeline([
        ("scaler", StandardScaler()),
        ("model", GaussianNB())
    ]),

    "AdaBoost": ada_model
}


# ------------------------------------------------------------
# PART 4: TRAIN AND EVALUATE MODELS
# ------------------------------------------------------------

results = []
confusion_matrices = {}

for name, model in models.items():

    # Train model
    model.fit(X_train, y_train)

    # Predict test data
    predictions = model.predict(X_test)

    # Evaluation metrics
    accuracy = accuracy_score(y_test, predictions)

    fault_precision = precision_score(
        y_test,
        predictions,
        labels=["Fault"],
        average="macro",
        zero_division=0
    )

    fault_recall = recall_score(
        y_test,
        predictions,
        labels=["Fault"],
        average="macro",
        zero_division=0
    )

    macro_f1 = f1_score(
        y_test,
        predictions,
        average="macro",
        zero_division=0
    )

    # Store results
    results.append({
        "Algorithm": name,
        "Accuracy": accuracy,
        "Fault Precision": fault_precision,
        "Fault Recall": fault_recall,
        "Macro F1": macro_f1
    })

    # Confusion matrix
    cm = confusion_matrix(
        y_test,
        predictions,
        labels=["Normal", "Warning", "Fault"]
    )

    confusion_matrices[name] = cm

    print("\n====================================")
    print("MODEL:", name)
    print("====================================")

    print("Accuracy:", round(accuracy, 3))
    print("Fault Precision:", round(fault_precision, 3))
    print("Fault Recall:", round(fault_recall, 3))
    print("Macro F1:", round(macro_f1, 3))

    print("\nClassification Report:")
    print(classification_report(
        y_test,
        predictions,
        labels=["Normal", "Warning", "Fault"],
        zero_division=0
    ))

    print("Confusion Matrix:")
    print(cm)


# ------------------------------------------------------------
# PART 5: COMPARE ALL ALGORITHMS
# ------------------------------------------------------------

results_df = pd.DataFrame(results)

print("\n========== MODEL COMPARISON ==========")
print(results_df.round(3).to_string(index=False))

# Save comparison results
results_df.to_csv("model_comparison_results.csv", index=False)

# Plot comparison
results_df.set_index("Algorithm")[
    ["Fault Precision", "Fault Recall", "Macro F1"]
].plot(kind="bar", figsize=(11, 6))

plt.title("Pump Classification Model Comparison")
plt.ylabel("Score")
plt.ylim(0, 1.05)
plt.xticks(rotation=20)
plt.legend(loc="lower right")
plt.tight_layout()
plt.savefig("model_comparison.png")
plt.show()


# ------------------------------------------------------------
# PART 6: CONFUSION MATRIX VISUALIZATION
# ------------------------------------------------------------

for name, cm in confusion_matrices.items():

    plt.figure(figsize=(6, 5))

    sns.heatmap(
        cm,
        annot=True,
        fmt="d",
        cmap="Blues",
        xticklabels=["Normal", "Warning", "Fault"],
        yticklabels=["Normal", "Warning", "Fault"]
    )

    plt.title(name + " - Confusion Matrix")
    plt.xlabel("Predicted Condition")
    plt.ylabel("Actual Condition")
    plt.tight_layout()

    filename = name.lower().replace(" ", "_") + "_confusion_matrix.png"
    plt.savefig(filename)

    plt.show()


# ------------------------------------------------------------
# PART 7: FEATURE IMPORTANCE AND NEW PUMP PREDICTION
# ------------------------------------------------------------

# Random Forest feature importance
rf_model = models["Random Forest"]

importance = pd.DataFrame({
    "Feature": X.columns,
    "Importance": rf_model.feature_importances_
})

importance = importance.sort_values(
    by="Importance",
    ascending=False
)

print("\n========== FEATURE IMPORTANCE ==========")
print(importance.to_string(index=False))

importance.plot(
    x="Feature",
    y="Importance",
    kind="bar",
    legend=False,
    figsize=(9, 5)
)

plt.title("Random Forest - Feature Importance")
plt.ylabel("Importance")
plt.tight_layout()
plt.savefig("feature_importance.png")
plt.show()


# Decision Tree visualization
plt.figure(figsize=(18, 9))

plot_tree(
    models["Decision Tree"],
    feature_names=X.columns,
    class_names=["Fault", "Normal", "Warning"],
    filled=True,
    rounded=True
)

plt.title("Decision Tree Pump Classification")
plt.tight_layout()
plt.savefig("decision_tree.png")
plt.show()


# Predict a new pump observation
new_pump = pd.DataFrame([{
    "Vibration": 6.2,
    "RPM": 1350,
    "Temperature": 82,
    "Pressure": 4.0,
    "Operating_Hours": 5500
}])

print("\n========== NEW PUMP PREDICTION ==========")
print(new_pump)

for name, model in models.items():

    prediction = model.predict(new_pump)[0]

    print(name, "prediction:", prediction)


